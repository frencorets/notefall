let lang = 'en';

export function setLang(pref) {
  const auto = (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
  lang = pref === 'en' || pref === 'es' ? pref : auto;
  document.documentElement.lang = lang;
  return lang;
}
export const getLang = () => lang;

export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}

// Plain-words instruction for a hint, e.g. "Hold D-pad up, then press A".
export function instruction(hint, laneLabel) {
  const m = hint.mod;
  if (!m.pad && !m.stick) return t('press', { b: laneLabel });
  const parts = [];
  if (m.pad) parts.push(t(m.pad > 0 ? 'padUp' : 'padDown'));
  if (m.stick) parts.push(t(m.stick > 0 ? 'stickUp' : 'stickDown'));
  return t('hold', { m: parts.join(t('and')), b: laneLabel });
}

// Solfège names for Spanish speakers.
const SOLFEGE = { C: 'Do', D: 'Re', E: 'Mi', F: 'Fa', G: 'Sol', A: 'La', B: 'Si' };
export function localNoteName(name) {
  if (lang !== 'es') return name;
  return name.replace(/^([A-G])/, (x) => SOLFEGE[x]);
}
